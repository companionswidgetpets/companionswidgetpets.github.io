const rules = new Intl.PluralRules('ru');

/** The form of a noun that goes with the number n: 1 рыбка, 2 рыбки, 5 рыбок. */
const plural = (n: number, one: string, few: string, many: string) => {
  const form = rules.select(n);
  return form === 'one' ? one : form === 'many' ? many : few;
};

/** A number with its noun: num(5, 'рыбка', 'рыбки', 'рыбок') is "5 рыбок". */
const num = (n: number, one: string, few: string, many: string) => `${n} ${plural(n, one, few, many)}`;

/** Ends a sentence with a full stop, unless it already ends with one: a Russian date
    does ("4 ноября 2026 г."), and a second stop after it would be wrong. */
const sentence = (text: string) => (text.endsWith('.') ? text : `${text}.`);

